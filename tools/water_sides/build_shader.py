"""Bake the sidewall vertex program from the active water/bed shaders.

The existing compiled water bundles remain byte-identical. Regenerate this
variant whenever their geometry changes; runtime binding rejects stale inputs.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "assets/water_sides"
WATER = ROOT / "assets/water_material_natural_candidate/async_rdc_water.gdshader"
BED = ROOT / "assets/water_material_natural_candidate/async_rdc_bed.gdshader"


def function(source, name):
    match = re.search(r"(?:void|float|vec[234]) " + name + r"\([^)]*\)\s*\{", source)
    if match is None:
        raise ValueError(name)
    end = match.end()
    level = 1
    while level:
        level += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[match.start():end]


def sha(data):
    return hashlib.sha256(data).hexdigest()


def build():
    water = WATER.read_text(encoding="utf-8")
    bed = BED.read_text(encoding="utf-8")
    legacy_water = (WATER.parent / "rdc_water.gdshader").read_text(encoding="utf-8")
    legacy_bed = (BED.parent / "rdc_bed.gdshader").read_text(encoding="utf-8")
    assert function(legacy_water, "vertex") == function(water, "vertex")
    assert function(legacy_bed, "bed_at") == function(bed, "bed_at")
    assert function(legacy_bed, "bed_cell") == function(bed, "bed_cell")
    prefix = water[:water.index("void vertex()")]
    prefix = re.sub(r"render_mode [^;]+;", "render_mode unshaded, cull_back, blend_mix, depth_draw_always;", prefix, count=1)
    optical = "\n".join(re.findall(r"^uniform .* rdc_\w+[^\n]*", water, re.M))
    bed_functions = function(bed, "bed_cell") + "\n\n" + function(bed, "bed_at")
    # Keep the entire actual water vertex body, including future XZ displacement.
    vertex = function(water, "vertex")
    vertex = vertex.replace("void vertex() {", "void vertex() {\n    vec3 boundary_normal = NORMAL;", 1)
    vertex = vertex[:-1] + """
    side_top_y = VERTEX.y;
    side_bottom_y = bed_at(UV);
    VERTEX.y = mix(min(side_bottom_y, side_top_y), side_top_y, COLOR.r);
    NORMAL = boundary_normal;
    side_position = (MODEL_MATRIX * vec4(VERTEX, 1.0)).xyz;
}
"""
    declarations = """
uniform vec2 side_min_xz = vec2(-15.96875);
uniform vec2 side_max_xz = vec2(15.96875);
uniform vec3 side_scatter_color : source_color = vec3(0.075, 0.32, 0.36);
uniform int side_debug = 0;
varying vec3 side_position;
varying float side_top_y;
varying float side_bottom_y;
"""
    fragment = (ROOT / "tools/water_sides/fragment.gdshaderinc").read_text(encoding="utf-8")
    generated = "// Generated by tools/water_sides/build_shader.py. Do not edit.\n" + prefix + "\n" + optical + "\n" + bed_functions + "\n" + declarations + "\n" + vertex + "\n" + fragment
    manifest = {
        "schema": 1,
        "water": "res://" + WATER.relative_to(ROOT).as_posix(),
        "water_sha256": sha(WATER.read_bytes()),
        "bed": "res://" + BED.relative_to(ROOT).as_posix(),
        "bed_sha256": sha(BED.read_bytes()),
        "shader": "res://assets/water_sides/water_sides.gdshader",
        "shader_sha256": sha(generated.encode()),
        "water_vertex_sha256": sha(function(water, "vertex").encode()),
        "bed_functions_sha256": sha(bed_functions.encode()),
        "equivalent_sources": {
            "res://assets/water_material_natural_candidate/rdc_water.gdshader": sha((WATER.parent / "rdc_water.gdshader").read_bytes()),
            "res://assets/water_material_natural_candidate/rdc_bed.gdshader": sha((BED.parent / "rdc_bed.gdshader").read_bytes())
        },
        "scope": "Godot visual boundary adaptation; verbatim water vertex body and bed sampling, independent side optics; no physics writes."
    }
    return generated, json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated, manifest = build()
    OUT.mkdir(exist_ok=True)
    for name, content in [("water_sides.gdshader", generated), ("geometry_manifest.json", manifest)]:
        path = OUT / name
        if args.check:
            assert path.read_bytes() == content.encode(), "stale: " + str(path)
        else:
            path.write_bytes(content.encode())
    print("WATER_SIDES_GEOMETRY_IDENTICAL" if args.check else "WATER_SIDES_SHADER_SAVED")
